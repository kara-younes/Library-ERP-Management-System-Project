-- =============================================
-- Fines / Payments Management
-- =============================================


-- 1. Display all fines.
SELECT *
FROM Fines;


-- 2. Display fines with member names.
SELECT
    F.FineID,
    F.MemberID,
    P.FirstName,
    P.LastName,
    F.BorrowingRecordID,
    F.FineAmount,
    F.PaymentStatus
FROM Fines F
JOIN Members M
    ON F.MemberID = M.MemberID
JOIN People P
    ON M.PersonID = P.PersonID;


-- 3. Display unpaid fines.
SELECT *
FROM Fines
WHERE PaymentStatus = 'Unpaid';


-- 4. Display paid fines.
SELECT *
FROM Fines
WHERE PaymentStatus = 'Paid';


-- 5. Find members with unpaid fines.
SELECT
    M.MemberID,
    P.FirstName,
    P.LastName,
    F.FineAmount
FROM Fines F
JOIN Members M
    ON F.MemberID = M.MemberID
JOIN People P
    ON M.PersonID = P.PersonID
WHERE F.PaymentStatus = 'Unpaid';


-- 6. Calculate total unpaid fine amount.
SELECT
    SUM(FineAmount) AS TotalUnpaidFineAmount
FROM Fines
WHERE PaymentStatus = 'Unpaid';


-- 7. Calculate total paid fine amount.
SELECT
    SUM(FineAmount) AS TotalPaidFineAmount
FROM Fines
WHERE PaymentStatus = 'Paid';


-- 8. Calculate total fines collected.
SELECT
    SUM(FineAmount) AS TotalFinesCollected
FROM Fines
WHERE PaymentStatus = 'Paid';


-- 9. Count fines by payment status.
SELECT
    PaymentStatus,
    COUNT(*) AS FineCount
FROM Fines
GROUP BY PaymentStatus;


-- 10. Find members with the highest total fines.
SELECT TOP 1
    F.MemberID,
    P.FirstName,
    P.LastName,
    SUM(F.FineAmount) AS TotalFines
FROM Fines F
JOIN Members M
    ON F.MemberID = M.MemberID
JOIN People P
    ON M.PersonID = P.PersonID
GROUP BY
    F.MemberID,
    P.FirstName,
    P.LastName
ORDER BY TotalFines DESC;


-- 11. Calculate total fines per member.
SELECT
    F.MemberID,
    P.FirstName,
    P.LastName,
    SUM(F.FineAmount) AS TotalFines
FROM Fines F
JOIN Members M
    ON F.MemberID = M.MemberID
JOIN People P
    ON M.PersonID = P.PersonID
GROUP BY
    F.MemberID,
    P.FirstName,
    P.LastName
ORDER BY TotalFines DESC;


-- 12. Find fines generated by overdue borrowing records.
SELECT
    F.*
FROM Fines F
JOIN BorrowingRecords B
    ON F.BorrowingRecordID = B.BorrowingRecordID
WHERE B.ActualReturnDate IS NULL
  AND B.DueDate < GETDATE();


-- 13. Display member, book, late days and fine amount.
SELECT
    P.FirstName,
    P.LastName,
    B.Title,
    DATEDIFF(DAY, BR.DueDate, BR.ActualReturnDate) AS LateDays,
    F.FineAmount
FROM Fines F
JOIN Members M
    ON F.MemberID = M.MemberID
JOIN People P
    ON M.PersonID = P.PersonID
JOIN BorrowingRecords BR
    ON F.BorrowingRecordID = BR.BorrowingRecordID
JOIN BookCopies BC
    ON BR.CopyID = BC.CopyID
JOIN Books B
    ON BC.BookID = B.BookID;


-- 14. Calculate average fine amount.
SELECT
    AVG(FineAmount) AS AverageFineAmount
FROM Fines;


-- 15. Display a complete fine/payment report.
SELECT
    F.FineID,
    P.FirstName,
    P.LastName,
    B.Title,
    BC.Barcode,
    BR.BorrowingDate,
    BR.DueDate,
    BR.ActualReturnDate,
    F.FineAmount,
    F.PaymentStatus
FROM Fines F
JOIN Members M
    ON F.MemberID = M.MemberID
JOIN People P
    ON M.PersonID = P.PersonID
JOIN BorrowingRecords BR
    ON F.BorrowingRecordID = BR.BorrowingRecordID
JOIN BookCopies BC
    ON BR.CopyID = BC.CopyID
JOIN Books B
    ON BC.BookID = B.BookID
ORDER BY F.FineID DESC;

